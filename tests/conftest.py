def add_reference(client, project, seed=0, **values):
    asset = client.post("/api/assets", files={"file": ("fixture.png", image_bytes(seed), "image/png")})
    assert asset.status_code == 201, asset.text
    response = client.post(f"/api/projects/{project['id']}/references", json={"asset_sha": asset.json()["id"], "title": f"测试参考 {seed}", **values})
    assert response.status_code == 201, response.text
    return response.json()["reference"]


def ready_reference(client, project, seed=0):
    ref = add_reference(client, project, seed)
    source = {**ref["source"], "rights": "owned", "rights_note": "Synthetic pixels generated by this regression test", "source_confirmed": True}
    ref = client.patch(f"/api/references/{ref['id']}", json={"expected_revision": ref["revision"], "decision": "keep", "source": source}).json()
    ref = client.post(f"/api/references/{ref['id']}/review", json={"expected_revision": ref["revision"], "review": review_data(ref["asset_sha"])}).json()
    ref = client.post(f"/api/references/{ref['id']}/card", json={"expected_revision": ref["revision"], "card": card_data()}).json()
    response = client.post(f"/api/references/{ref['id']}/accept", json={"expected_revision": ref["revision"]})
    assert response.status_code == 200, response.text
    return response.json()
