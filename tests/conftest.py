def image_bytes(seed: int = 0, size: tuple[int, int] = (800, 1200)) -> bytes:
    """Synthetic test pixels, not a real photograph or a vision accuracy benchmark."""
    image = Image.new("RGB", size, (100 + seed % 80, 140, 120))
    draw = ImageDraw.Draw(image)
    draw.rectangle((size[0] // 4, size[1] // 5, size[0] * 3 // 4, size[1] * 4 // 5), fill=(190, 190 + seed % 50, 170))
    draw.text((20, 20), f"SYNTHETIC TEST FIXTURE {seed}", fill=(20, 35, 45))
    stream = io.BytesIO()
    image.save(stream, "PNG")
    return stream.getvalue()


